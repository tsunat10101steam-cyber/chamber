let LANG = "en";
function setLang(l) {
  LANG = I18N[l] ? l : "en";
  try { localStorage.setItem("lang", LANG); } catch { /* 저장 못 해도 이번 실행엔 적용 */ }
}
(() => {
  let saved = null;
  try { saved = localStorage.getItem("lang"); } catch { /* 없음 */ }
  const nav = (navigator.language || "en").toLowerCase();
  LANG = saved && I18N[saved] ? saved : (I18N[nav.split("-")[0]] ? nav.split("-")[0] : "en");
})();

function t(key, p = {}) {
  const s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (p[k] ?? m));
}
